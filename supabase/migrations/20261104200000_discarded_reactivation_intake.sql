-- One-time discarded-lead intake. No recurring capture of discarded leads.
BEGIN;
SET LOCAL lock_timeout='5s';

CREATE TABLE IF NOT EXISTS public.reactivation_intake_batches (
 id uuid PRIMARY KEY,
 requested_by uuid REFERENCES public.profiles(id),
 requested_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.reactivation_intake (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id uuid NOT NULL REFERENCES public.reactivation_intake_batches(id) ON DELETE RESTRICT,
 lead_id bigint NOT NULL REFERENCES public.leads(id) ON DELETE RESTRICT,
 lead_name text NOT NULL,
 interest text,
 previous_broker_id uuid REFERENCES public.profiles(id),
 previous_broker_name text,
 source_status text NOT NULL CHECK(source_status='descartado'),
 source_last_activity_at timestamptz NOT NULL,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','converted','skipped')),
 case_id bigint UNIQUE REFERENCES public.reactivation_cases(id) ON DELETE RESTRICT,
 requested_at timestamptz NOT NULL DEFAULT now(),
 resolved_at timestamptz,
 resolution_reason text,
 UNIQUE(batch_id,lead_id),
 CHECK((status='pending' AND case_id IS NULL AND resolved_at IS NULL)
  OR (status='converted' AND case_id IS NOT NULL AND resolved_at IS NOT NULL)
  OR (status='skipped' AND case_id IS NULL AND resolved_at IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS one_pending_reactivation_intake_per_lead
 ON public.reactivation_intake(lead_id) WHERE status='pending';
CREATE INDEX IF NOT EXISTS reactivation_intake_pending_order
 ON public.reactivation_intake(requested_at,id) WHERE status='pending';
ALTER TABLE public.reactivation_intake_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reactivation_intake ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS reactivation_intake_batches_admin_read ON public.reactivation_intake_batches;
CREATE POLICY reactivation_intake_batches_admin_read ON public.reactivation_intake_batches
 FOR SELECT TO authenticated USING(public.is_crm_admin());
DROP POLICY IF EXISTS reactivation_intake_admin_read ON public.reactivation_intake;
CREATE POLICY reactivation_intake_admin_read ON public.reactivation_intake
 FOR SELECT TO authenticated USING(public.is_crm_admin());
REVOKE ALL ON public.reactivation_intake_batches,public.reactivation_intake FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.reactivation_intake_batches,public.reactivation_intake TO authenticated;

CREATE OR REPLACE FUNCTION public.enqueue_discarded_reactivation(p_batch_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE existed boolean; entry public.leads; queued integer:=0;
BEGIN
 IF NOT (public.is_crm_admin() OR COALESCE(auth.role(),'')='service_role'
  OR (auth.uid() IS NULL AND COALESCE(current_setting('role',true),'none') IN ('none','postgres')))
  THEN RAISE EXCEPTION 'Somente administradores podem incluir descartados no remalho.' USING ERRCODE='42501'; END IF;
 IF p_batch_id IS NULL THEN RAISE EXCEPTION 'Informe o identificador da importação.'; END IF;
 -- Use the same intake lock as the hourly processor. A retried batch is a
 -- frozen snapshot; it must not collect leads discarded after the first call.
 PERFORM pg_advisory_xact_lock(71624511);
 SELECT EXISTS(SELECT 1 FROM public.reactivation_intake_batches WHERE id=p_batch_id) INTO existed;
 IF NOT existed THEN
  INSERT INTO public.reactivation_intake_batches(id,requested_by) VALUES(p_batch_id,auth.uid());
  FOR entry IN SELECT l.* FROM public.leads l
   WHERE l.status='descartado'
    AND NOT EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.lead_id=l.id AND c.status='active')
    AND NOT EXISTS(SELECT 1 FROM public.reactivation_intake i WHERE i.lead_id=l.id AND i.status='pending')
   ORDER BY l.id FOR UPDATE OF l
  LOOP
   INSERT INTO public.reactivation_intake(batch_id,lead_id,lead_name,interest,previous_broker_id,previous_broker_name,source_status,source_last_activity_at)
   VALUES(p_batch_id,entry.id,entry.nome,entry.interesse,entry.corretor_id,entry.corretor,entry.status,COALESCE(entry.last_activity_at,entry.created_at,now()));
   queued:=queued+1;
  END LOOP;
 END IF;
 RETURN jsonb_build_object('batchId',p_batch_id,'queued',queued,'existingBatch',existed,
  'pendingCount',(SELECT count(*) FROM public.reactivation_intake WHERE status='pending'),
  'convertedCount',(SELECT count(*) FROM public.reactivation_intake WHERE status='converted'),
  'skippedCount',(SELECT count(*) FROM public.reactivation_intake WHERE status='skipped'));
END;$$;
REVOKE ALL ON FUNCTION public.enqueue_discarded_reactivation(uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.enqueue_discarded_reactivation(uuid) TO authenticated,service_role;

CREATE OR REPLACE FUNCTION public.get_reactivation_intake()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF NOT public.is_crm_admin() THEN RAISE EXCEPTION 'Somente administradores podem consultar a fila de entrada do remalho.' USING ERRCODE='42501'; END IF;
 RETURN jsonb_build_object(
  'pendingCount',(SELECT count(*) FROM public.reactivation_intake WHERE status='pending'),
  'convertedCount',(SELECT count(*) FROM public.reactivation_intake WHERE status='converted'),
  'skippedCount',(SELECT count(*) FROM public.reactivation_intake WHERE status='skipped'),
  'items',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',id,'lead_id',lead_id,'lead_name',lead_name,'interest',interest,
    'previous_broker_name',previous_broker_name,'requested_at',requested_at,'status',status) ORDER BY requested_at,id)
   FROM public.reactivation_intake WHERE status='pending'),'[]'::jsonb));
END;$$;
REVOKE ALL ON FUNCTION public.get_reactivation_intake() FROM PUBLIC,anon,service_role;
GRANT EXECUTE ON FUNCTION public.get_reactivation_intake() TO authenticated;

CREATE OR REPLACE FUNCTION public.process_reactivation_queue(p_limit integer DEFAULT 500) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE s public.reactivation_settings; l public.leads; intake public.reactivation_intake;
 v_case_id bigint; worker_name text; moved integer:=0; intake_moved integer:=0; intake_skipped integer:=0;
 pending_case record; batch_limit integer:=GREATEST(1,LEAST(COALESCE(p_limit,500),500));
BEGIN
 IF NOT (public.is_crm_admin() OR COALESCE(auth.role(),'')='service_role'
  OR (auth.uid() IS NULL AND COALESCE(current_setting('role',true),'none') IN ('none','postgres')))
  THEN RAISE EXCEPTION 'Somente administradores podem processar a fila.' USING ERRCODE='42501'; END IF;
 IF NOT pg_try_advisory_xact_lock(71624511) THEN RETURN jsonb_build_object('moved',0,'intakeMoved',0,'intakeSkipped',0,'busy',true); END IF;
 SELECT * INTO s FROM public.reactivation_settings WHERE id FOR UPDATE;
 SELECT nome INTO worker_name FROM public.profiles WHERE id=s.worker_id AND ativo;
 IF s.enabled AND worker_name IS NOT NULL THEN
  FOR intake IN SELECT i.* FROM public.reactivation_intake i WHERE i.status='pending'
   ORDER BY i.requested_at,i.id LIMIT batch_limit FOR UPDATE OF i SKIP LOCKED
  LOOP
   SELECT * INTO l FROM public.leads WHERE id=intake.lead_id FOR UPDATE;
   IF NOT FOUND OR l.status IS DISTINCT FROM 'descartado' THEN
    UPDATE public.reactivation_intake SET status='skipped',resolved_at=now(),resolution_reason='A situação do lead mudou antes da entrada no remalho.' WHERE id=intake.id;
    intake_skipped:=intake_skipped+1;
   ELSIF EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.lead_id=l.id AND c.status='active') THEN
    UPDATE public.reactivation_intake SET status='skipped',resolved_at=now(),resolution_reason='O lead já está em acompanhamento no remalho.' WHERE id=intake.id;
    intake_skipped:=intake_skipped+1;
   ELSE
    INSERT INTO public.reactivation_cases(lead_id,worker_id,lead_name,interest,previous_broker_id,previous_broker_name,inactive_since)
    VALUES(l.id,s.worker_id,l.nome,l.interesse,intake.previous_broker_id,intake.previous_broker_name,intake.source_last_activity_at) RETURNING id INTO v_case_id;
    UPDATE public.leads SET corretor_id=s.worker_id,corretor=worker_name,status='atendimento',
     status_changed_at=(now() AT TIME ZONE 'America/Sao_Paulo')::date WHERE id=l.id;
    PERFORM public.ensure_reactivation_task(v_case_id);
    UPDATE public.reactivation_intake SET status='converted',case_id=v_case_id,resolved_at=now(),resolution_reason='Descartado incluído no remalho por solicitação administrativa.' WHERE id=intake.id;
    moved:=moved+1;intake_moved:=intake_moved+1;
   END IF;
  END LOOP;
  -- Ordinary inactivity intake retains its original eligibility. In particular,
  -- a contact closed without interest is not automatically recycled again.
  IF moved<batch_limit THEN
   FOR l IN SELECT lead.* FROM public.leads lead
    WHERE lead.status IN ('novo','contato','atendimento','visita','proposta') AND lead.last_activity_at<=now()-interval '14 days'
     AND (lead.corretor_id IS NOT NULL OR NULLIF(btrim(lead.corretor),'') IS NOT NULL)
     AND lead.corretor_id IS DISTINCT FROM s.worker_id AND lead.corretor IS DISTINCT FROM worker_name
     AND NOT EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.lead_id=lead.id AND c.status='active')
    ORDER BY lead.last_activity_at,lead.id LIMIT batch_limit-moved FOR UPDATE OF lead SKIP LOCKED
   LOOP
    INSERT INTO public.reactivation_cases(lead_id,worker_id,lead_name,interest,previous_broker_id,previous_broker_name,inactive_since)
    VALUES(l.id,s.worker_id,l.nome,l.interesse,l.corretor_id,l.corretor,l.last_activity_at) RETURNING id INTO v_case_id;
    UPDATE public.leads SET corretor_id=s.worker_id,corretor=worker_name WHERE id=l.id;
    PERFORM public.ensure_reactivation_task(v_case_id);
    moved:=moved+1;
   END LOOP;
  END IF;
 END IF;
 FOR pending_case IN SELECT id FROM public.reactivation_cases WHERE status='active' LOOP PERFORM public.ensure_reactivation_task(pending_case.id); END LOOP;
 RETURN jsonb_build_object('moved',moved,'intakeMoved',intake_moved,'intakeSkipped',intake_skipped,'enabled',s.enabled);
END;$$;
REVOKE ALL ON FUNCTION public.process_reactivation_queue(integer) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.process_reactivation_queue(integer) TO authenticated,service_role;
NOTIFY pgrst,'reload schema';
COMMIT;
