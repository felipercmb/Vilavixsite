-- Reativação: instalação inerte até um administrador configurar a funcionária.
BEGIN;
SET LOCAL lock_timeout = '5s';

ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS last_activity_at timestamptz;
-- Historical edits had no general updated_at. Use only observable evidence;
-- do not treat the automatic creation of follow-up tasks as a broker contact.
UPDATE public.leads l SET last_activity_at=LEAST(now(),COALESCE(GREATEST(
 l.created_at,
 (l.status_changed_at::timestamp + interval '1 day') AT TIME ZONE 'America/Sao_Paulo',
 (SELECT max(c.created_at) FROM public.comments c WHERE c.lead_id=l.id
  AND c.autor NOT IN ('Roleta VilaVix','Automação','Sistema'))
),now())) WHERE last_activity_at IS NULL;
CREATE INDEX IF NOT EXISTS leads_reactivation_inactivity ON public.leads(last_activity_at,id)
 WHERE status IN ('novo','contato','atendimento','visita','proposta');

CREATE TABLE IF NOT EXISTS public.reactivation_settings (
 id boolean PRIMARY KEY DEFAULT true CHECK(id),
 enabled boolean NOT NULL DEFAULT false,
 worker_id uuid REFERENCES public.profiles(id),
 broker_ids uuid[] NOT NULL DEFAULT '{}',
 cursor_position integer NOT NULL DEFAULT -1,
 updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.reactivation_settings(id) VALUES(true) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS public.reactivation_cases (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id bigint NOT NULL REFERENCES public.leads(id) ON DELETE RESTRICT,
 worker_id uuid NOT NULL REFERENCES public.profiles(id),
 lead_name text NOT NULL, interest text,
 previous_broker_id uuid REFERENCES public.profiles(id), previous_broker_name text,
 inactive_since timestamptz NOT NULL,
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','reactivated','closed')),
 received_at timestamptz NOT NULL DEFAULT now(),
 next_contact_on date NOT NULL DEFAULT ((now() AT TIME ZONE 'America/Sao_Paulo')::date),
 finished_at timestamptz, returned_broker_id uuid REFERENCES public.profiles(id), returned_broker_name text
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_reactivation_per_lead ON public.reactivation_cases(lead_id) WHERE status='active';
CREATE INDEX IF NOT EXISTS reactivation_daily_queue ON public.reactivation_cases(worker_id,status,next_contact_on,id);
CREATE TABLE IF NOT EXISTS public.reactivation_notes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_id bigint NOT NULL REFERENCES public.reactivation_cases(id) ON DELETE RESTRICT,
 author_id uuid NOT NULL REFERENCES public.profiles(id), author_name text NOT NULL,
 body text NOT NULL CHECK(length(btrim(body)) BETWEEN 3 AND 4000),
 outcome text NOT NULL CHECK(outcome IN ('sem_resposta','em_conversa','retorno_agendado','reativado','sem_interesse')),
 request_id uuid NOT NULL UNIQUE,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.tasks ADD COLUMN IF NOT EXISTS reactivation_case_id bigint REFERENCES public.reactivation_cases(id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX IF NOT EXISTS one_pending_reactivation_task ON public.tasks(reactivation_case_id)
 WHERE reactivation_case_id IS NOT NULL AND NOT concluida AND tipo_auto='reativacao';

CREATE OR REPLACE FUNCTION public.has_reactivation_access() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT public.is_crm_admin() OR EXISTS(
  SELECT 1 FROM public.reactivation_settings s JOIN public.profiles p ON p.id=s.worker_id
  WHERE s.id AND s.worker_id=auth.uid() AND p.ativo
 );
$$;
REVOKE ALL ON FUNCTION public.has_reactivation_access() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.has_reactivation_access() TO authenticated;
ALTER TABLE public.reactivation_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reactivation_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reactivation_notes ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS reactivation_settings_read ON public.reactivation_settings;
CREATE POLICY reactivation_settings_read ON public.reactivation_settings FOR SELECT TO authenticated USING(public.is_crm_admin());
DROP POLICY IF EXISTS reactivation_cases_read ON public.reactivation_cases;
CREATE POLICY reactivation_cases_read ON public.reactivation_cases FOR SELECT TO authenticated
 USING(public.is_crm_member() AND (public.is_crm_admin() OR worker_id=auth.uid() OR returned_broker_id=auth.uid()));
DROP POLICY IF EXISTS reactivation_notes_read ON public.reactivation_notes;
CREATE POLICY reactivation_notes_read ON public.reactivation_notes FOR SELECT TO authenticated
 USING(EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.id=case_id));
REVOKE ALL ON public.reactivation_settings,public.reactivation_cases,public.reactivation_notes FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.reactivation_settings,public.reactivation_cases,public.reactivation_notes TO authenticated;

-- This derives current receiving eligibility. Removing a broker from the live
-- campaign/legacy lists also pauses them in the recovery round, without a timer.
CREATE OR REPLACE FUNCTION public.reactivation_receiving_brokers()
RETURNS TABLE(id uuid,nome text) LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT p.id,p.nome FROM public.profiles p
 WHERE p.ativo AND (
  EXISTS(SELECT 1 FROM public.campaigns c WHERE c.routing_configured AND c.routing_enabled
   AND c.effective_status='ACTIVE' AND p.id=ANY(c.broker_ids) AND COALESCE((c.weights->>p.id::text)::numeric,1)>0)
  OR EXISTS(SELECT 1 FROM public.roleta_regras r WHERE r.ativo AND r.agentes @> jsonb_build_array(p.nome))
  OR EXISTS(SELECT 1 FROM public.config c WHERE c.key='roleta' AND (
   CASE WHEN COALESCE((c.value->>'enabled')::boolean,false)
    THEN COALESCE(c.value->'agentNames','[]'::jsonb) @> jsonb_build_array(p.nome)
    ELSE c.value->>'fixedAgent'=p.nome END))
 ) ORDER BY p.nome,p.id;
$$;
REVOKE ALL ON FUNCTION public.reactivation_receiving_brokers() FROM PUBLIC,anon,authenticated,service_role;

CREATE OR REPLACE FUNCTION public.reactivation_overview() RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
DECLARE s public.reactivation_settings; result jsonb;
BEGIN
 IF NOT public.is_crm_admin() THEN RAISE EXCEPTION 'Somente administradores podem configurar a reativação.' USING ERRCODE='42501'; END IF;
 SELECT * INTO s FROM public.reactivation_settings WHERE id;
 SELECT jsonb_build_object('settings',to_jsonb(s),'receivingBrokers',COALESCE((SELECT jsonb_agg(to_jsonb(b)) FROM public.reactivation_receiving_brokers() b),'[]'::jsonb),
  'eligibleCount',(SELECT count(*) FROM public.leads l WHERE l.status IN ('novo','contato','atendimento','visita','proposta')
   AND l.last_activity_at<=now()-interval '14 days' AND (l.corretor_id IS NOT NULL OR NULLIF(btrim(l.corretor),'') IS NOT NULL)
   AND (s.worker_id IS NULL OR (l.corretor_id IS DISTINCT FROM s.worker_id AND l.corretor IS DISTINCT FROM (SELECT nome FROM public.profiles WHERE id=s.worker_id)))
   AND NOT EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.lead_id=l.id AND c.status='active')),
  'schedulerInstalled',EXISTS(SELECT 1 FROM pg_extension WHERE extname='pg_cron')) INTO result;
 RETURN result;
END;$$;
REVOKE ALL ON FUNCTION public.reactivation_overview() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.reactivation_overview() TO authenticated;

CREATE OR REPLACE FUNCTION public.save_reactivation_settings(p_worker_id uuid,p_broker_ids uuid[],p_enabled boolean)
RETURNS public.reactivation_settings LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE s public.reactivation_settings; bid uuid;
BEGIN
 IF NOT public.is_crm_admin() THEN RAISE EXCEPTION 'Somente administradores podem configurar a reativação.' USING ERRCODE='42501'; END IF;
 SELECT * INTO s FROM public.reactivation_settings WHERE id FOR UPDATE;
 IF p_worker_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_worker_id AND ativo)
  THEN RAISE EXCEPTION 'Selecione uma conta ativa para a funcionária.'; END IF;
 IF p_enabled AND (p_worker_id IS NULL OR COALESCE(cardinality(p_broker_ids),0)=0)
  THEN RAISE EXCEPTION 'Vincule a funcionária e os participantes antes de ativar.'; END IF;
 IF p_worker_id IS DISTINCT FROM s.worker_id AND EXISTS(SELECT 1 FROM public.reactivation_cases WHERE status='active')
  THEN RAISE EXCEPTION 'Há contatos em acompanhamento. Finalize a fila antes de trocar a funcionária.'; END IF;
 FOREACH bid IN ARRAY COALESCE(p_broker_ids,'{}'::uuid[]) LOOP
  IF bid=p_worker_id OR NOT EXISTS(SELECT 1 FROM public.reactivation_receiving_brokers() b WHERE b.id=bid)
   THEN RAISE EXCEPTION 'A roleta aceita apenas corretores que recebem leads; a funcionária não pode participar.'; END IF;
 END LOOP;
 IF cardinality(p_broker_ids) IS DISTINCT FROM (SELECT count(DISTINCT x)::int FROM unnest(p_broker_ids) x) AND p_broker_ids IS NOT NULL
  THEN RAISE EXCEPTION 'Há participantes repetidos.'; END IF;
 UPDATE public.reactivation_settings SET worker_id=p_worker_id,broker_ids=COALESCE(p_broker_ids,'{}'),enabled=p_enabled,
  cursor_position=CASE WHEN broker_ids IS DISTINCT FROM COALESCE(p_broker_ids,'{}') THEN -1 ELSE cursor_position END,updated_at=now()
 WHERE id RETURNING * INTO s;
 RETURN s;
END;$$;
REVOKE ALL ON FUNCTION public.save_reactivation_settings(uuid,uuid[],boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.save_reactivation_settings(uuid,uuid[],boolean) TO authenticated;

-- Plain invoker guards distinguish a normal API request from a controlled
-- SECURITY DEFINER operation. All write RPCs below check the caller themselves.
CREATE OR REPLACE FUNCTION public.track_lead_activity() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
BEGIN
 IF TG_OP='INSERT' THEN NEW.last_activity_at:=now(); RETURN NEW; END IF;
 IF ROW(NEW.nome,NEW.email,NEW.telefone,NEW.interesse,NEW.imovel_id,NEW.status,NEW.notas,NEW.prioridade,NEW.orcamento,NEW.corretor_id,NEW.corretor)
  IS DISTINCT FROM ROW(OLD.nome,OLD.email,OLD.telefone,OLD.interesse,OLD.imovel_id,OLD.status,OLD.notas,OLD.prioridade,OLD.orcamento,OLD.corretor_id,OLD.corretor)
 THEN NEW.last_activity_at:=now();
 ELSIF current_user='postgres' OR COALESCE(auth.role(),'')='service_role'
  THEN NEW.last_activity_at:=GREATEST(OLD.last_activity_at,LEAST(NEW.last_activity_at,now()));
 ELSE NEW.last_activity_at:=OLD.last_activity_at; END IF;
 RETURN NEW;
END;$$;
REVOKE ALL ON FUNCTION public.track_lead_activity() FROM PUBLIC,anon,authenticated,service_role;
CREATE OR REPLACE TRIGGER leads_activity_clock BEFORE INSERT OR UPDATE ON public.leads FOR EACH ROW EXECUTE FUNCTION public.track_lead_activity();
CREATE OR REPLACE FUNCTION public.track_contact_activity() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF TG_TABLE_NAME='comments' THEN
  IF auth.uid() IS NOT NULL AND public.is_crm_member() THEN
   UPDATE public.leads SET last_activity_at=now() WHERE id=NEW.lead_id;
  END IF;
 ELSIF auth.uid() IS NOT NULL AND public.is_crm_member() THEN
  IF (TG_OP='INSERT' AND NOT COALESCE(NEW.auto_gerada,false)) OR
   (TG_OP='UPDATE' AND ROW(NEW.titulo,NEW.descricao,NEW.tipo,NEW.data,NEW.hora,NEW.concluida)
    IS DISTINCT FROM ROW(OLD.titulo,OLD.descricao,OLD.tipo,OLD.data,OLD.hora,OLD.concluida)) THEN
   UPDATE public.leads SET last_activity_at=now() WHERE id=NEW.lead_id;
  END IF;
 END IF;
 RETURN NEW;
END;$$;
REVOKE ALL ON FUNCTION public.track_contact_activity() FROM PUBLIC,anon,authenticated,service_role;
CREATE OR REPLACE TRIGGER comments_activity_clock AFTER INSERT ON public.comments FOR EACH ROW EXECUTE FUNCTION public.track_contact_activity();
CREATE OR REPLACE TRIGGER tasks_activity_clock AFTER INSERT OR UPDATE ON public.tasks FOR EACH ROW EXECUTE FUNCTION public.track_contact_activity();

CREATE OR REPLACE FUNCTION public.guard_reactivation_task() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
BEGIN
 IF current_user='postgres' OR COALESCE(auth.role(),'')='service_role' THEN
  IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
 END IF;
 IF (TG_OP<>'INSERT' AND OLD.reactivation_case_id IS NOT NULL) OR (TG_OP<>'DELETE' AND NEW.reactivation_case_id IS NOT NULL)
  THEN RAISE EXCEPTION 'Registre o atendimento na área de reativação para concluir ou reagendar esta tarefa.' USING ERRCODE='42501'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;$$;
REVOKE ALL ON FUNCTION public.guard_reactivation_task() FROM PUBLIC,anon,authenticated,service_role;
CREATE OR REPLACE TRIGGER tasks_guard_reactivation BEFORE INSERT OR UPDATE OR DELETE ON public.tasks FOR EACH ROW EXECUTE FUNCTION public.guard_reactivation_task();

CREATE OR REPLACE FUNCTION public.ensure_reactivation_task(p_case_id bigint) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE c public.reactivation_cases; worker_name text;
BEGIN
 SELECT * INTO c FROM public.reactivation_cases WHERE id=p_case_id AND status='active';
 IF NOT FOUND THEN RETURN; END IF;
 SELECT nome INTO worker_name FROM public.profiles WHERE id=c.worker_id AND ativo;
 IF worker_name IS NULL THEN RETURN; END IF;
 INSERT INTO public.tasks(tipo,titulo,descricao,lead_id,data,hora,concluida,prioridade,auto_gerada,exige_decisao,tipo_auto,corretor,reactivation_case_id)
 VALUES('ligacao','Reativar: '||c.lead_name,'Registre a tentativa na área de reativação e defina o próximo contato.',c.lead_id,c.next_contact_on,'09:00',false,'alta',true,false,'reativacao',worker_name,c.id)
 ON CONFLICT(reactivation_case_id) WHERE reactivation_case_id IS NOT NULL AND NOT concluida AND tipo_auto='reativacao' DO NOTHING;
END;$$;
REVOKE ALL ON FUNCTION public.ensure_reactivation_task(bigint) FROM PUBLIC,anon,authenticated,service_role;

CREATE OR REPLACE FUNCTION public.process_reactivation_queue(p_limit integer DEFAULT 500) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE s public.reactivation_settings; l public.leads; case_id bigint; worker_name text; moved integer:=0; pending_case record;
BEGIN
 IF NOT (public.is_crm_admin() OR COALESCE(auth.role(),'')='service_role'
  OR (auth.uid() IS NULL AND COALESCE(current_setting('role',true),'none') IN ('none','postgres')))
  THEN RAISE EXCEPTION 'Somente administradores podem processar a fila.' USING ERRCODE='42501'; END IF;
 IF NOT pg_try_advisory_xact_lock(71624511) THEN RETURN jsonb_build_object('moved',0,'busy',true); END IF;
 SELECT * INTO s FROM public.reactivation_settings WHERE id FOR UPDATE;
 SELECT nome INTO worker_name FROM public.profiles WHERE id=s.worker_id AND ativo;
 IF s.enabled AND worker_name IS NOT NULL THEN
  FOR l IN SELECT lead.* FROM public.leads lead
   WHERE lead.status IN ('novo','contato','atendimento','visita','proposta') AND lead.last_activity_at<=now()-interval '14 days'
    AND (lead.corretor_id IS NOT NULL OR NULLIF(btrim(lead.corretor),'') IS NOT NULL)
    AND lead.corretor_id IS DISTINCT FROM s.worker_id AND lead.corretor IS DISTINCT FROM worker_name
    AND NOT EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.lead_id=lead.id AND c.status='active')
   ORDER BY lead.last_activity_at,lead.id LIMIT GREATEST(1,LEAST(COALESCE(p_limit,500),500)) FOR UPDATE OF lead SKIP LOCKED
  LOOP
   INSERT INTO public.reactivation_cases(lead_id,worker_id,lead_name,interest,previous_broker_id,previous_broker_name,inactive_since)
   VALUES(l.id,s.worker_id,l.nome,l.interesse,l.corretor_id,l.corretor,l.last_activity_at) RETURNING id INTO case_id;
   UPDATE public.leads SET corretor_id=s.worker_id,corretor=worker_name WHERE id=l.id;
   PERFORM public.ensure_reactivation_task(case_id);
   moved:=moved+1;
  END LOOP;
 END IF;
 FOR pending_case IN SELECT id FROM public.reactivation_cases WHERE status='active' LOOP PERFORM public.ensure_reactivation_task(pending_case.id); END LOOP;
 RETURN jsonb_build_object('moved',moved,'enabled',s.enabled);
END;$$;
REVOKE ALL ON FUNCTION public.process_reactivation_queue(integer) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.process_reactivation_queue(integer) TO authenticated,service_role;

CREATE OR REPLACE FUNCTION public.record_reactivation_contact(p_case_id bigint,p_body text,p_outcome text,p_next_on date,p_request_id uuid)
RETURNS public.reactivation_cases LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE c public.reactivation_cases; who text; prior public.reactivation_notes;
BEGIN
 SELECT * INTO c FROM public.reactivation_cases WHERE id=p_case_id FOR UPDATE;
 IF NOT FOUND OR NOT public.is_crm_member() OR NOT(public.is_crm_admin() OR (c.worker_id=auth.uid() AND public.has_reactivation_access()))
  THEN RAISE EXCEPTION 'Este acompanhamento não está disponível para sua conta.' USING ERRCODE='42501'; END IF;
 SELECT * INTO prior FROM public.reactivation_notes WHERE request_id=p_request_id;
 IF FOUND THEN
  IF prior.case_id<>p_case_id OR prior.author_id<>auth.uid() OR prior.body<>btrim(p_body) OR prior.outcome<>p_outcome
   THEN RAISE EXCEPTION 'Identificador de tentativa já utilizado.'; END IF;
  RETURN c;
 END IF;
 IF c.status<>'active' THEN RAISE EXCEPTION 'Este acompanhamento já foi encerrado.'; END IF;
 IF length(btrim(COALESCE(p_body,''))) NOT BETWEEN 3 AND 4000 OR p_request_id IS NULL THEN RAISE EXCEPTION 'Descreva o contato em 3 a 4.000 caracteres.'; END IF;
 IF p_outcome IS NULL OR p_outcome NOT IN ('sem_resposta','em_conversa','retorno_agendado') THEN RAISE EXCEPTION 'Selecione o resultado da tentativa.'; END IF;
 IF p_next_on IS NULL OR p_next_on<(now() AT TIME ZONE 'America/Sao_Paulo')::date OR p_next_on>(now() AT TIME ZONE 'America/Sao_Paulo')::date+30
  THEN RAISE EXCEPTION 'Agende o próximo contato entre hoje e os próximos 30 dias.'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.leads WHERE id=c.lead_id AND corretor_id=c.worker_id) THEN RAISE EXCEPTION 'O responsável do lead mudou. Atualize a fila.'; END IF;
 SELECT nome INTO who FROM public.profiles WHERE id=auth.uid();
 INSERT INTO public.reactivation_notes(case_id,author_id,author_name,body,outcome,request_id) VALUES(c.id,auth.uid(),who,btrim(p_body),p_outcome,p_request_id);
 INSERT INTO public.comments(lead_id,autor,texto) VALUES(c.lead_id,who,'Reativação ('||p_outcome||'): '||btrim(p_body));
 UPDATE public.tasks SET concluida=true WHERE reactivation_case_id=c.id AND tipo_auto='reativacao' AND NOT concluida;
 UPDATE public.reactivation_cases SET next_contact_on=p_next_on WHERE id=c.id RETURNING * INTO c;
 PERFORM public.ensure_reactivation_task(c.id);
 RETURN c;
END;$$;
REVOKE ALL ON FUNCTION public.record_reactivation_contact(bigint,text,text,date,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.record_reactivation_contact(bigint,text,text,date,uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.finish_reactivation(p_case_id bigint,p_body text,p_reactivated boolean,p_request_id uuid)
RETURNS public.reactivation_cases LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE s public.reactivation_settings; c public.reactivation_cases; chosen record; who text; prior public.reactivation_notes;
BEGIN
 -- Every redistribution locks the same cursor before the case/lead: retries
 -- neither advance the round nor assign the same lead twice.
 SELECT * INTO s FROM public.reactivation_settings WHERE id FOR UPDATE;
 SELECT * INTO c FROM public.reactivation_cases WHERE id=p_case_id FOR UPDATE;
 IF NOT FOUND OR NOT public.is_crm_member() OR NOT(public.is_crm_admin() OR (c.worker_id=auth.uid() AND public.has_reactivation_access()))
  THEN RAISE EXCEPTION 'Este acompanhamento não está disponível para sua conta.' USING ERRCODE='42501'; END IF;
 SELECT * INTO prior FROM public.reactivation_notes WHERE request_id=p_request_id;
 IF FOUND THEN
  IF prior.case_id<>p_case_id OR prior.author_id<>auth.uid() OR prior.body<>btrim(p_body) OR prior.outcome<>(CASE WHEN p_reactivated THEN 'reativado' ELSE 'sem_interesse' END)
   THEN RAISE EXCEPTION 'Identificador de tentativa já utilizado.'; END IF;
  RETURN c;
 END IF;
 IF c.status<>'active' THEN RAISE EXCEPTION 'Este acompanhamento já foi encerrado; confira o responsável no histórico.'; END IF;
 IF length(btrim(COALESCE(p_body,''))) NOT BETWEEN 3 AND 4000 OR p_request_id IS NULL OR p_reactivated IS NULL THEN RAISE EXCEPTION 'Descreva o resultado em 3 a 4.000 caracteres.'; END IF;
 PERFORM 1 FROM public.leads WHERE id=c.lead_id AND corretor_id=c.worker_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'O responsável do lead mudou. Atualize a fila.'; END IF;
 SELECT NULL::uuid AS id,NULL::text AS nome,NULL::integer AS position INTO chosen;
 IF p_reactivated THEN
  SELECT p.id,p.nome,team.ordinality::int-1 AS position INTO chosen
  FROM unnest(s.broker_ids) WITH ORDINALITY team(id,ordinality)
  JOIN public.reactivation_receiving_brokers() p ON p.id=team.id AND p.id<>c.worker_id
  ORDER BY CASE WHEN team.ordinality-1>s.cursor_position THEN 0 ELSE 1 END,team.ordinality LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'A nova roleta está sem corretor disponível. O lead continua com a reativação; peça ao administrador para revisar os participantes.'; END IF;
 END IF;
 SELECT nome INTO who FROM public.profiles WHERE id=auth.uid();
 INSERT INTO public.reactivation_notes(case_id,author_id,author_name,body,outcome,request_id)
 VALUES(c.id,auth.uid(),who,btrim(p_body),CASE WHEN p_reactivated THEN 'reativado' ELSE 'sem_interesse' END,p_request_id);
 INSERT INTO public.comments(lead_id,autor,texto) VALUES(c.lead_id,who,
  CASE WHEN p_reactivated THEN 'Lead reativado e encaminhado para '||chosen.nome||': ' ELSE 'Reativação encerrada sem interesse: ' END||btrim(p_body));
 UPDATE public.tasks SET concluida=true WHERE reactivation_case_id=c.id AND tipo_auto='reativacao' AND NOT concluida;
 IF p_reactivated THEN
  UPDATE public.leads SET corretor_id=chosen.id,corretor=chosen.nome,status='novo',status_changed_at=(now() AT TIME ZONE 'America/Sao_Paulo')::date,
   routing_source='reactivation',routing_status='assigned',routing_reason='Roleta independente de leads reativados',routing_assigned_at=now() WHERE id=c.lead_id;
  UPDATE public.reactivation_cases SET status='reactivated',finished_at=now(),returned_broker_id=chosen.id,returned_broker_name=chosen.nome WHERE id=c.id RETURNING * INTO c;
  UPDATE public.reactivation_settings SET cursor_position=chosen.position WHERE id;
  INSERT INTO public.tasks(tipo,titulo,descricao,lead_id,data,hora,concluida,prioridade,auto_gerada,tipo_auto,corretor)
  VALUES('ligacao','Primeiro contato: lead reativado — '||c.lead_name,'Leia o histórico da reativação antes de abordar o contato.',c.lead_id,
   (now() AT TIME ZONE 'America/Sao_Paulo')::date,to_char(now() AT TIME ZONE 'America/Sao_Paulo','HH24:MI'),false,'alta',true,'reativacao_retorno',chosen.nome);
 ELSE
  UPDATE public.leads SET status='descartado',status_changed_at=(now() AT TIME ZONE 'America/Sao_Paulo')::date WHERE id=c.lead_id;
  UPDATE public.reactivation_cases SET status='closed',finished_at=now() WHERE id=c.id RETURNING * INTO c;
 END IF;
 RETURN c;
END;$$;
REVOKE ALL ON FUNCTION public.finish_reactivation(bigint,text,boolean,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.finish_reactivation(bigint,text,boolean,uuid) TO authenticated;

-- A normal edit cannot bypass the reactivation round or close an active case.
CREATE OR REPLACE FUNCTION public.guard_reactivation_lead() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
BEGIN
 IF current_user='postgres' OR COALESCE(auth.role(),'')='service_role' THEN RETURN NEW; END IF;
 IF EXISTS(SELECT 1 FROM public.reactivation_cases c WHERE c.lead_id=OLD.id AND c.status='active')
  AND (ROW(NEW.corretor_id,NEW.corretor) IS DISTINCT FROM ROW(OLD.corretor_id,OLD.corretor)
   OR (NEW.status IN ('fechado','descartado') AND NEW.status IS DISTINCT FROM OLD.status))
